import re, subprocess, time, uuid
from playwright.sync_api import sync_playwright, expect
CAT=".msg--cat:not(.msg--typing)"; BASE="http://localhost:5173"; SHOTS="tests/e2e/screenshots"
import os; os.makedirs(SHOTS, exist_ok=True)
email=f"e2e-{uuid.uuid4().hex[:6]}@example.com"; pw="correct horse"
errors=[]
def step(n): print("✓", n)
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={"width":1360,"height":860})
    pg=ctx.new_page()
    pg.on("console", lambda m: m.type=="error" and errors.append(m.text))
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.goto(BASE); expect(pg.get_by_role("heading", level=1)).to_contain_text("cat who listens")
    pg.screenshot(path=f"{SHOTS}/landing.png", full_page=True); step("landing renders")
    pg.get_by_role("link", name="Start talking").first.click(); expect(pg).to_have_url(re.compile("/register"))
    pg.get_by_role("button", name="Create account").click()
    expect(pg.get_by_text("Enter your email address.")).to_be_visible(); step("client validation")
    pg.get_by_label("Email").fill(email); pg.get_by_label("Password", exact=True).fill(pw)
    pg.screenshot(path=f"{SHOTS}/register.png")
    pg.get_by_role("button", name="Create account").click()
    expect(pg).to_have_url(BASE+"/chat"); expect(pg.get_by_text("No conversations yet")).to_be_visible(); step("register -> chat, empty state")
    pg.screenshot(path=f"{SHOTS}/chat-home.png")
    pg.get_by_role("button", name="I've had a really long day").click()
    expect(pg).to_have_url(re.compile(r"/chat/[0-9a-f-]{36}"))
    expect(pg.get_by_text("Miso is thinking it over")).to_be_visible(); pg.screenshot(path=f"{SHOTS}/typing.png"); step("typing indicator")
    expect(pg.get_by_text("What feels hardest right now?")).to_be_visible(timeout=10000)
    expect(pg.locator(".rich li")).to_have_count(2); step("first reply from backend, list formatting")
    box=pg.get_by_label("Message to Miso"); box.fill("Work was stressful and\nI barely slept"); box.press("Enter")
    expect(pg.locator(CAT)).to_have_count(2, timeout=10000)
    assert "Work was stressful and\nI barely slept" in pg.locator(".msg__bubble--user").nth(1).inner_text(); step("Enter sends, multiline preserved")
    expect(pg.locator(".convos__link")).to_have_count(1); expect(pg.locator(".convos__title")).to_have_text("I've had a really long day"); step("sidebar lists titled conversation")
    pg.screenshot(path=f"{SHOTS}/conversation.png")
    url=pg.url; pg.reload(); expect(pg.locator(".msg")).to_have_count(4); step("reload keeps session + history")
    # AI failure path
    subprocess.run(["pkill","-f","stub_ai.py"]); time.sleep(0.5)
    box=pg.get_by_label("Message to Miso"); box.fill("Are you there?"); box.press("Enter")
    expect(pg.get_by_text("Miso couldn't reply just now.")).to_be_visible(timeout=10000)
    expect(pg.get_by_text("Your message is saved")).to_be_visible(); expect(pg.get_by_role("button", name="Try again")).to_be_visible()
    pg.screenshot(path=f"{SHOTS}/ai-failure.png"); step("503 AI_UNAVAILABLE handled, saved message reconciled")
    subprocess.Popen(["python3","tests/e2e/stub_ai.py","9100"]); time.sleep(0.8)
    pg.get_by_role("button", name="Try again").click()
    expect(pg.get_by_text("Miso couldn't reply just now.")).to_have_count(0, timeout=10000); expect(pg.locator(CAT)).to_have_count(3); step("retry after recovery")
    # new conversation, then delete it
    pg.get_by_role("link", name="New conversation").click(); expect(pg).to_have_url(BASE+"/chat"); expect(pg.locator(".welcome")).to_be_visible()
    pg.get_by_label("Message to Miso").fill("Second chat"); pg.get_by_role("button", name="Send message").click()
    expect(pg.locator(CAT)).to_have_count(1, timeout=10000); expect(pg.locator(".convos__link")).to_have_count(2)
    pg.get_by_role("button", name="Delete conversation: Second chat").click()
    expect(pg.get_by_role("dialog")).to_be_visible(); pg.screenshot(path=f"{SHOTS}/delete-dialog.png")
    pg.get_by_role("button", name="Delete conversation", exact=True).click()
    expect(pg.get_by_text("Conversation deleted")).to_be_visible(); expect(pg).to_have_url(BASE+"/chat"); expect(pg.locator(".convos__link")).to_have_count(1); step("delete with confirm + toast + redirect")
    pg.goto(BASE+"/chat/00000000-0000-0000-0000-000000000000"); expect(pg.get_by_text("This conversation isn't here")).to_be_visible(); step("unknown conversation -> not-found state")
    pg.goto(BASE+"/nope"); expect(pg.get_by_text("This page wandered off")).to_be_visible(); step("404 page")
    pg.goto(BASE+"/chat"); pg.get_by_role("button", name="Sign out").click(); expect(pg).to_have_url(re.compile("/login")); step("logout")
    pg.goto(BASE+"/chat"); expect(pg).to_have_url(re.compile("/login")); step("protected route redirects")
    pg.get_by_label("Email").fill(email); pg.get_by_label("Password", exact=True).fill("wrong password"); pg.get_by_role("button", name="Sign in").click()
    expect(pg.get_by_text("Email or password is incorrect.")).to_be_visible(); pg.screenshot(path=f"{SHOTS}/login-error.png"); step("invalid credentials")
    pg.get_by_label("Password", exact=True).fill(pw); pg.get_by_role("button", name="Sign in").click(); expect(pg).to_have_url(BASE+"/chat")
    expect(pg.locator(".convos__link")).to_have_count(1); step("login restores conversations")
    # register duplicate
    ctx2=b.new_context(); p2=ctx2.new_page(); p2.goto(BASE+"/register")
    p2.get_by_label("Email").fill(email); p2.get_by_label("Password", exact=True).fill(pw); p2.get_by_role("button", name="Create account").click()
    expect(p2.get_by_text("An account with that email already exists.")).to_be_visible(); step("duplicate email")
    # expired/invalid token mid-session
    pg.evaluate("() => { for (const s of [localStorage, sessionStorage]) if (s.getItem('miso.token')) s.setItem('miso.token','bogus') }")
    pg.reload(); expect(pg).to_have_url(re.compile("/login")); step("invalid stored token -> sign in")
    # mobile
    m=b.new_context(viewport={"width":390,"height":844}, is_mobile=True, has_touch=True); mp=m.new_page()
    mp.goto(BASE); mp.screenshot(path=f"{SHOTS}/m-landing.png", full_page=True)
    assert mp.evaluate("document.documentElement.scrollWidth <= innerWidth"), "horizontal overflow on landing"
    mp.goto(BASE+"/login"); mp.get_by_label("Email").fill(email); mp.get_by_label("Password", exact=True).fill(pw); mp.get_by_role("button", name="Sign in").click()
    expect(mp).to_have_url(BASE+"/chat"); mp.locator(".convos__link").first.wait_for(state="attached")
    mp.screenshot(path=f"{SHOTS}/m-chat-home.png")
    mp.get_by_role("button", name="Open conversations").click(); expect(mp.locator(".sidebar.is-open")).to_be_visible(); mp.wait_for_timeout(350)
    mp.screenshot(path=f"{SHOTS}/m-drawer.png"); mp.locator(".convos__link").first.click()
    expect(mp.locator(".msg")).to_have_count(7, timeout=8000); mp.wait_for_timeout(300); mp.screenshot(path=f"{SHOTS}/m-conversation.png")
    assert mp.evaluate("document.documentElement.scrollWidth <= innerWidth"), "horizontal overflow in chat"
    box=mp.get_by_label("Message to Miso").bounding_box(); assert box["y"]+box["height"] <= 844; step("mobile: drawer, conversation, composer in viewport, no overflow")
    # backend down
    subprocess.run(["pkill","-f","uvicorn app.main:app"]); time.sleep(0.8)
    mp.reload(); expect(mp.get_by_text("Miso's server isn't answering")).to_be_visible(timeout=10000); mp.screenshot(path=f"{SHOTS}/m-server-down.png"); step("backend down -> unreachable state (session kept)")
    b.close()
print("console errors:", [e for e in errors if "Failed to load resource" not in e] or "none")
